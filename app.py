def login_required(fn):
    @wraps(fn)
    def wrapper(*args, **kwargs):
        if not session.get('logged_in'):
            return redirect(url_for('login', next=request.path))
        return fn(*args, **kwargs)
    return wrapper

def csrf_check():
    token = request.form.get('csrf','')
    return bool(token and session.get('csrf') and hmac.compare_digest(token, session['csrf']))

def get_fields(table):
    return TABLES[table][1]

def parse_values(table, form):
    values={}
    for key,label,kind,required in get_fields(table):
        value=form.get(key,'').strip()
        if required is True and not value:
            raise ValueError(f'Το πεδίο «{label}» είναι υποχρεωτικό.')
        if kind=='number':
            if value == '': value=None
            else:
                try: value=float(value.replace(',','.'))
                except ValueError: raise ValueError(f'Το πεδίο «{label}» πρέπει να είναι αριθμός.')
        values[key]=value or None
    return values

@app.after_request
def secure_headers(response):
    response.headers['X-Content-Type-Options']='nosniff'
    response.headers['X-Frame-Options']='DENY'
    response.headers['Referrer-Policy']='same-origin'
    response.headers['Cache-Control']='no-store'
    return response

@app.route('/login', methods=['GET','POST'])
def login():
    if session.get('logged_in'): return redirect(url_for('home'))
    error=''
    if request.method=='POST':
        if not csrf_check(): error='Η φόρμα έληξε. Δοκίμασε ξανά.'
        elif hmac.compare_digest(request.form.get('username',''),APP_USERNAME) and hmac.compare_digest(request.form.get('password',''),APP_PASSWORD):
            session.clear(); session['logged_in']=True; session['csrf']=secrets.token_urlsafe(32)
            return redirect(request.args.get('next') or url_for('home'))
        else: error='Λάθος όνομα χρήστη ή κωδικός.'
    if not session.get('csrf'): session['csrf']=secrets.token_urlsafe(32)
    body='''<section class="panel login"><h2>Σύνδεση</h2><p class="muted">Προσωπική πρόσβαση στο εκτροφείο.</p>{% if error %}<div class="notice error">{{ error }}</div>{% endif %}<form method="post"><input type="hidden" name="csrf" value="{{ csrf }}"><div style="margin-bottom:14px"><label>Όνομα χρήστη</label><input name="username" autocomplete="username" required></div><div style="margin-bottom:18px"><label>Κωδικός πρόσβασης</label><input type="password" name="password" autocomplete="current-password" required></div><button class="btn primary" type="submit">Είσοδος</button></form></section>'''
    return render_page('Σύνδεση',render_template_string(body,error=error,csrf=session['csrf']))

