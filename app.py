def form_body(table, record=None, error=''):
    label,fields=TABLES[table]
    is_edit=record is not None
    parts=[f'<section class="panel"><h2>{"Επεξεργασία" if is_edit else "Νέα εγγραφή"}: {label}</h2>']
    if error: parts.append('<div class="notice error">'+error.replace('&','&amp;').replace('<','&lt;').replace('>','&gt;')+'</div>')
    parts.append('<form method="post"><input type="hidden" name="csrf" value="{{ csrf }}"><div class="fields">')
    for key,field_label,kind,required in fields:
        val=(record or {}).get(key,'')
        val='' if val is None else str(val)
        esc=val.replace('&','&amp;').replace('<','&lt;').replace('>','&gt;').replace('"','&quot;')
        req=' required' if required is True else ''
        cls='field full' if kind=='textarea' else 'field'
        parts.append(f'<div class="{cls}"><label for="{key}">{field_label}{" *" if req else ""}</label>')
        if kind.startswith('select:'):
            options=kind.split(':',1)[1].split('|'); parts.append(f'<select id="{key}" name="{key}"{req}><option value="">— Επιλογή —</option>')
            for option in options:
                sel=' selected' if val==option else ''
                parts.append(f'<option value="{option}"{sel}>{option}</option>')
            parts.append('</select>')
        elif kind=='textarea': parts.append(f'<textarea id="{key}" name="{key}" placeholder="{field_label}">{esc}</textarea>')
        else:
            typ='number' if kind=='number' else ('date' if kind=='date' else ('email' if kind=='email' else 'text'))
            step=' step="0.01" min="0"' if kind=='number' else ''
            parts.append(f'<input id="{key}" type="{typ}" name="{key}" value="{esc}"{step}{req}>')
        parts.append('</div>')
    parts.append('</div><div class="row" style="margin-top:20px"><button class="btn primary" type="submit">Αποθήκευση</button><a class="btn" href="{{ url_for(\'records\',table=table) }}">Επιστροφή</a></div></form>')
    if is_edit: parts.append('<hr style="border-color:var(--line);margin:22px 0"><form method="post" action="{{ url_for(\'delete_record\',table=table,record_id=record_id) }}" onsubmit="return confirm(\'Να διαγραφεί οριστικά αυτή η εγγραφή;\')"><input type="hidden" name="csrf" value="{{ csrf }}"><button class="btn danger" type="submit">Διαγραφή εγγραφής</button></form>')
    parts.append('</section>')
    return render_template_string(''.join(parts),csrf=session['csrf'],table=table,record_id=(record or {}).get('id',''))

@app.route('/records/<table>/new',methods=['GET','POST'])
@login_required
def new_record(table):
    if table not in TABLES: abort(404)
    error=''
    if request.method=='POST':
        if not csrf_check(): abort(400)
        try:
            vals=parse_values(table,request.form); keys=list(vals.keys())
            with db() as con:
                con.execute(sql.SQL('INSERT INTO {} ({}) VALUES ({})').format(sql.Identifier(table),sql.SQL(',').join(map(sql.Identifier,keys)),sql.SQL(',').join(sql.Placeholder()*len(keys))),list(vals.values()))
            flash('Η εγγραφή αποθηκεύτηκε.'); return redirect(url_for('records',table=table))
        except ValueError as e: error=str(e)
        except Exception: app.logger.exception('Could not create record'); error='Δεν αποθηκεύτηκε η εγγραφή. Έλεγξε τα στοιχεία και ξαναδοκίμασε.'
    return render_page('Νέα εγγραφή',form_body(table,error=error))

@app.route('/records/<table>/<int:record_id>',methods=['GET','POST'])
@login_required
def edit_record(table,record_id):
    if table not in TABLES: abort(404)
    with db() as con: record=con.execute(sql.SQL('SELECT * FROM {} WHERE id=%s').format(sql.Identifier(table)),(record_id,)).fetchone()
    if not record: abort(404)
    error=''
    if request.method=='POST':
        if not csrf_check(): abort(400)
        try:
            vals=parse_values(table,request.form); keys=list(vals.keys())
            with db() as con:
                con.execute(sql.SQL('UPDATE {} SET {} WHERE id=%s').format(sql.Identifier(table),sql.SQL(',').join(sql.SQL('{}=%s').format(sql.Identifier(k)) for k in keys)),list(vals.values())+[record_id])
            flash('Οι αλλαγές αποθηκεύτηκαν.'); return redirect(url_for('records',table=table))
        except ValueError as e: error=str(e)
        except Exception: app.logger.exception('Could not update record'); error='Δεν αποθηκεύτηκαν οι αλλαγές. Έλεγξε τα στοιχεία και ξαναδοκίμασε.'
    return render_page('Επεξεργασία',form_body(table,record,error))

